#ifndef NYX_RUNTIME_HPP
#define NYX_RUNTIME_HPP

/*--------------------------------------------------------------------------------------------------------------------*/

#include "common.hpp"

/*--------------------------------------------------------------------------------------------------------------------*/

namespace nyx {

/*--------------------------------------------------------------------------------------------------------------------*/

/* RUNTIME                                                                                                            */
/*--------------------------------------------------------------------------------------------------------------------*/

/**
 * @brief RAII guard initializing and finalizing Nyx memory management.
 */
class Runtime
{
public:
    /*----------------------------------------------------------------------------------------------------------------*/

    /**
     * @brief Initializes Nyx memory management.
     */
    Runtime()
    {
        nyx_memory_initialize();
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    /**
     * @brief Finalizes Nyx memory management.
     */
    ~Runtime()
    {
        nyx_memory_finalize();
    }

    /*----------------------------------------------------------------------------------------------------------------*/

    Runtime(const Runtime &) = delete;
    Runtime &operator=(const Runtime &) = delete;

    /*----------------------------------------------------------------------------------------------------------------*/
};

/*--------------------------------------------------------------------------------------------------------------------*/

} /* namespace nyx */

/*--------------------------------------------------------------------------------------------------------------------*/

#endif /* NYX_RUNTIME_HPP */

